#!/usr/bin/env bash
# Turn the published species redirect map into the snippet fly/Caddyfile imports, and
# reload Caddy when it changed (beeatlas-zsi8).
#
#   fly/caddy-redirects.sh
#
# The site build writes species-redirects.map into the site root, one
# "<folded path> <accepted path>" pair per line. Apache read that file per request;
# Caddy reads its config once, so the map has to become config. merge-swap.sh runs this
# after every publish in the image, and the Machine's startup runs it before Caddy
# starts. Nothing is reloaded when the snippet comes out unchanged, which is almost
# always: a fold is a curatorial decision, made a few times a year.
#
# A missing map yields a snippet with no rules. A failed reload exits non-zero, but the
# publish that called this does not fail on it: the build also writes a meta-refresh
# page at each folded URL, so a reader is still forwarded, only more slowly.

set -euo pipefail

map="${SITE_ROOT:-/data/htdocs}/species-redirects.map"
dir="${CADDY_SNIPPETS:-/data/caddy}"
out="$dir/species-redirects.caddy"
mkdir -p "$dir"

tmp=$(mktemp "$out.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
    echo "# GENERATED by fly/caddy-redirects.sh from $map; do not edit."
    if [[ -f "$map" ]]; then
        # Apache matched the folded directory with or without index.html; so does this.
        echo 'map {path} {species_redirect} {'
        awk '!/^#/ && NF == 2 { printf "\t%s %s\n\t%sindex.html %s\n", $1, $2, $1, $2 }' "$map"
        echo '}'
        echo '@species_folded not vars {species_redirect} ""'
        echo 'redir @species_folded {species_redirect} 301'
    fi
} > "$tmp"

if [[ -f "$out" ]] && cmp -s "$tmp" "$out"; then
    exit 0
fi
mv "$tmp" "$out"
trap - EXIT
echo "caddy-redirects: $out rewritten ($(grep -c 'index.html ' "$out" || true) folded names)"

# Reload only a Caddy that is running; at startup this runs before Caddy does.
if curl -fsS -o /dev/null --max-time 2 http://localhost:2019/config/ 2> /dev/null; then
    caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile
    echo "caddy-redirects: Caddy reloaded"
fi
